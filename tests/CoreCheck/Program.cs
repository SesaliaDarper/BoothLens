using BoothLens.Core;
using BoothLens.Core.Booth;
using BoothLens.Core.Data;
using BoothLens.Core.Library;
using BoothLens.Core.Util;

var paths = new AppPaths(Path.Combine(Path.GetTempPath(), "BoothLensCore-" + Guid.NewGuid().ToString("N")));
var db = new Db(paths.DbPath); db.EnsureSchema();
var store = new ItemStore(db);
using var client = new BoothClient();
var catalog = new Catalog(client, store, paths);
var tasks = Enumerable.Range(0,3).Select(_ => catalog.Add("https://booth.pm/zh-cn/items/8962830", default));
var items = await Task.WhenAll(tasks);
if (items.Any(i => i.Id != 8962830 || !i.Title.Contains("Salt"))) throw new Exception("Wrong live item");
if(client.RequestCount != 2 || client.ImageRequestCount != 1) throw new Exception($"Cache counts: {client.RequestCount}, {client.ImageRequestCount}");
await catalog.Add("8962830", default);
if(client.RequestCount != 2) throw new Exception("Cache made extra request");
if(store.Search("8962830",1,10,null,false).Total!=1 || store.Search("Salt",1,10,null,false).Total!=1) throw new Exception("Search failed");
var detail = await catalog.Description(8962830, default);
if(!detail.Sections.Any(s => s.Title.Contains("同梱"))) throw new Exception("Missing full description sections");
var beforeDetail = client.RequestCount;
await catalog.Description(8962830, default);
if(client.RequestCount != beforeDetail) throw new Exception("Description refetched");
var reopened = new Catalog(client, new ItemStore(new Db(paths.DbPath)), paths);
await reopened.Add("https://komado.booth.pm/items/8962830?foo=bar", default);
if(client.RequestCount != beforeDetail) throw new Exception("Reopened cache missed");
if(store.Search("ソル",1,10,null,false).Total != 1) throw new Exception("Two-character query failed");
store.Search("\" OR 1=1 --",1,10,null,false);
var search = await catalog.Search("Salt",default);
if(search.Count==0 || search.Any(s=>s.Thumb!=null)) throw new Exception("Keyword search failed");
if(SafeName.Clean("a/b:c").Contains('/')) throw new Exception("Safe name failure");
Console.WriteLine(System.Text.Json.JsonSerializer.Serialize(new { passed=true,item=items[0].Title, images=client.ImageRequestCount, requests=client.RequestCount, sections=detail.Sections.Count, hits=search.Count, data=paths.Root }));
